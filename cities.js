// Find best matching city for a free-text query.
// Strategy: case-insensitive prefix match wins; otherwise substring match;
// otherwise null (caller will warn the user).
function findCity(query) {
  if (!query) return null;
  const q = query.trim().toLowerCase();
  if (!q) return null;
  // Strip anything after the first comma so "Mumbai, Maharashtra" still matches "Mumbai".
  const head = q.split(',')[0].trim();
  let prefix = null, contains = null;
  for (const c of CITIES) {
    const name = c.n.toLowerCase();
    if (name === head) return c;
    if (!prefix && name.startsWith(head)) prefix = c;
    if (!contains && name.includes(head)) contains = c;
  }
  return prefix || contains;
}
